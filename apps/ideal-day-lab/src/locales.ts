export const dictionaries: Record<Locale, Record<keyof typeof en, string>> = { 'en-US': en, 'zh-CN': zh };

export function translate(locale: Locale, key: keyof typeof en, vars?: TranslationVars): string {
  const template = dictionaries[locale][key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

